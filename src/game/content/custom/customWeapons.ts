import { GearDef, QuestDef, WeaponDef, WeaponLevel } from "../types";

function levels(
    base: Omit<WeaponLevel, "description"> & { description?: string },
    ...changes: (Partial<WeaponLevel> & { description: string })[]
): WeaponLevel[] {
    const result: WeaponLevel[] = [{ description: "", ...base }];
    for (const change of changes) {
        result.push({ ...result[result.length - 1], ...change });
    }
    return result;
}

function evolvedLevels(
    first: Omit<WeaponLevel, "description"> & { description: string },
): WeaponLevel[] {
    return levels(
        first,
        { damage: Math.round(first.damage * 1.15), description: "+15% damage." },
        { damage: Math.round(first.damage * 1.3), description: "+15% damage." },
    );
}

